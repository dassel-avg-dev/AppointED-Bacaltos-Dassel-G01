@register.simple_tag
def icon(name, classes="w-5 h-5"):
    path = ICONS.get(name, "")
    return format_html(
        '<svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" '
        'stroke-width="1.5" stroke="currentColor" class="{}" aria-hidden="true">'
        '<path stroke-linecap="round" stroke-linejoin="round" d="{}"/></svg>',
        classes,
        mark_safe(path),
    )


@register.simple_tag
def status_badge(status):
    label = dict(Status.choices).get(status, status)
    return format_html('<span class="badge badge-{}">{}</span>', str(status).lower(), label)


@register.simple_tag
def slot_time(slot):
    """9:00 AM – 10:00 AM"""
    return f"{time_filter(slot.start_time, 'g:i A')} – {time_filter(slot.end_time, 'g:i A')}"


@register.simple_tag
def slot_when(slot):
    """Mon, Nov 9 · 9:00 AM – 10:00 AM"""
    return f"{date_filter(slot.slot_date, 'D, M j')} · {slot_time(slot)}"


@register.filter
def friendly_day(value):
    delta = (value - timezone.localdate()).days
    if delta == 0:
        return "Today"
    if delta == 1:
        return "Tomorrow"
    if delta == -1:
        return "Yesterday"
    return date_filter(value, "D, M j")


@register.filter
def initials(name):
    parts = (name or "").split()
    return "".join(p[0] for p in parts[:2]).upper() or "?"
